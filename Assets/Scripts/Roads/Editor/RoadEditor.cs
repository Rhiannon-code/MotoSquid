using UnityEditor;
using UnityEngine;

namespace MotoSquid.Roads
{
    [CustomEditor(typeof(Road))]
    public class RoadEditor : Editor
    {
        const float LabelEvery = 100f;
        static readonly string[] Hidden = { "m_Script", nameof(Road.generated), nameof(Road.edited), nameof(Road.handShaped) };

        // Nodes move a road, not its Transform: a road dragged as a whole slides off the junctions it was built to meet.
        void OnEnable() => Tools.hidden = true;
        void OnDisable() => Tools.hidden = false;

        public override void OnInspectorGUI()
        {
            var road = (Road)target;
            EditorGUILayout.HelpBox(Status(road), road.edited ? MessageType.Info : MessageType.None);

            serializedObject.Update();
            EditorGUI.BeginChangeCheck();
            DrawPropertiesExcluding(serializedObject, Hidden);
            bool changed = EditorGUI.EndChangeCheck();
            serializedObject.ApplyModifiedProperties();
            if (changed)
            {
                Undo.RecordObjects(new Object[] { road, road.GetComponent<UnityEngine.Splines.SplineContainer>() }, "Edit road");
                road.edited = true;
                if (!road.handShaped) road.ShapeFromRecipe();
                EditorUtility.SetDirty(road);
                RoadNodeEdits.MarkStale(road);
            }

            EditorGUILayout.Space();
            var network = road.GetComponentInParent<RoadNetwork>();
            using (new EditorGUI.DisabledScope(network == null))
                if (GUILayout.Button("Rebuild network surface"))
                    EditorApplication.delayCall += () => RoadNetworkBuild.Rebuild(network);
            using (new EditorGUI.DisabledScope(!road.handShaped || road.recipe.IsEmpty))
                if (GUILayout.Button("Reshape from recipe (drops hand-moved knots)"))
                {
                    Undo.RecordObjects(new Object[] { road, road.GetComponent<UnityEngine.Splines.SplineContainer>() }, "Reshape road from recipe");
                    road.handShaped = false;
                    road.ShapeFromRecipe();
                    EditorUtility.SetDirty(road);
                    RoadNodeEdits.MarkStale(road);
                }
            using (new EditorGUI.DisabledScope(!road.edited))
                if (GUILayout.Button("Hand back to the layout (Update Roads may replace it)"))
                {
                    Undo.RecordObject(road, "Hand road back to the layout");
                    road.edited = false;
                    road.handShaped = false;
                    EditorUtility.SetDirty(road);
                }
        }

        static string Status(Road road) =>
            road.handShaped ? "Hand-shaped: the knots are the road. The recipe below no longer drives it. Update Roads leaves it alone."
            : road.edited ? "Edited by hand: the recipe drives the knots, and Update Roads leaves it alone."
            : road.generated ? "Generated by its layout: Update Roads replaces it. Editing anything here keeps it yours."
            : road.recipe.IsEmpty ? "Hand-made road: its knots are the road." : "Driven by its recipe.";

        RoadPath labelled;
        int labelledShape;

        // Station marks along the road, for setting bank zones, air zones and height points.
        void OnSceneGUI()
        {
            var road = (Road)target;
            if (road.Spline == null || road.Spline.Count < 2) return;
            int shape = RoadNodes.ShapeHash(road);
            if (labelled == null || shape != labelledShape)
            {
                labelled = RoadPath.Sample(road);
                labelledShape = shape;
            }
            var path = labelled;
            int step = Mathf.Max(1, Mathf.RoundToInt(LabelEvery / path.Spacing));
            for (int i = 0; i < path.Count; i += step)
                Handles.Label(path.Point(i, 0f) + Vector3.up * 2f, $"{i * path.Spacing:0} m");
        }
    }
}
